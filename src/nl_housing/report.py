"""Keep the README "Key insights" in sync with the analysis notebook (D-033).

The notebook renders its key findings from computed numbers and calls :func:`write_key_findings`, which

1. writes them to ``docs/KEY_FINDINGS.md`` (the generated source of truth), and
2. replaces the block between :data:`START_MARKER` and :data:`END_MARKER` in ``README.md`` with the same text.

Nothing else in the README is touched. ``tests/test_report.py`` fails when the README block and
``docs/KEY_FINDINGS.md`` differ (someone edited the README by hand), and the CI ``pipeline`` job re-runs the
notebook on fresh CBS data and fails when either file changes (a CBS revision changed a number). The same job
compares every text output of the re-executed notebook with the committed one (:func:`text_outputs`; images are
ignored because PNG bytes depend on the font renderer)::

    python -m nl_housing.report --compare-notebook committed.ipynb executed.ipynb
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from pathlib import Path

from nl_housing import config

logger = logging.getLogger(__name__)

START_MARKER = (
    "<!-- key-findings:start (generated by notebooks/01_affordability_findings.ipynb, section 6; do not edit) -->"
)
END_MARKER = "<!-- key-findings:end -->"
KEY_FINDINGS_NAME = "KEY_FINDINGS.md"


def key_findings_path(root: Path = config.REPO_ROOT) -> Path:
    """Location of the generated key-findings file (``docs/KEY_FINDINGS.md``)."""
    return root / "docs" / KEY_FINDINGS_NAME


def readme_path(root: Path = config.REPO_ROOT) -> Path:
    """Location of the README."""
    return root / "README.md"


def _marker_positions(text: str) -> tuple[int, int]:
    """Start and end index of the generated block (markers included); exactly one pair must exist."""
    if text.count(START_MARKER) != 1 or text.count(END_MARKER) != 1:
        raise ValueError("README must contain exactly one key-findings start marker and one end marker")
    start = text.index(START_MARKER)
    end = text.index(END_MARKER)
    if end < start:
        raise ValueError("key-findings end marker comes before the start marker")
    return start, end + len(END_MARKER)


def extract_block(text: str) -> str:
    """The generated text between the markers, without the markers and surrounding blank lines."""
    start, end = _marker_positions(text)
    inner = text[start + len(START_MARKER) : end - len(END_MARKER)]
    return inner.strip("\n")


def replace_block(text: str, block: str) -> str:
    """Return ``text`` with the content between the markers replaced by ``block`` (idempotent)."""
    start, end = _marker_positions(text)
    return text[:start] + f"{START_MARKER}\n{block.strip(chr(10))}\n{END_MARKER}" + text[end:]


def write_key_findings(block: str, root: Path = config.REPO_ROOT) -> bool:
    """Write ``docs/KEY_FINDINGS.md`` and the README block. Returns True if either file changed."""
    block = block.strip("\n")
    changed = False

    kf_path = key_findings_path(root)
    new_kf = block + "\n"
    if not kf_path.exists() or kf_path.read_text(encoding="utf-8") != new_kf:
        kf_path.write_text(new_kf, encoding="utf-8")
        changed = True

    rm_path = readme_path(root)
    old_readme = rm_path.read_text(encoding="utf-8")
    new_readme = replace_block(old_readme, block)
    if new_readme != old_readme:
        rm_path.write_text(new_readme, encoding="utf-8")
        changed = True

    logger.info("Key findings %s", "updated" if changed else "unchanged")
    return changed


def text_outputs(notebook: Path) -> list[str]:
    """Every non-image output of a notebook (stream text, Markdown, HTML, plain text), in cell order.

    Images (``image/png``) and the ``<Figure ...>`` placeholder that accompanies them are left out, so two runs on
    the same data compare equal on any platform.
    """
    nb = json.loads(notebook.read_text(encoding="utf-8"))
    outputs: list[str] = []
    for cell in nb.get("cells", []):
        for out in cell.get("outputs", []):
            if out.get("output_type") == "stream":
                outputs.append("".join(out.get("text", [])))
                continue
            data = {k: v for k, v in out.get("data", {}).items() if k != "image/png"}
            if "image/png" in out.get("data", {}):
                data.pop("text/plain", None)
            for mime in sorted(data):
                value = data[mime]
                outputs.append(f"{mime}: " + ("".join(value) if isinstance(value, list) else str(value)))
    return outputs


def compare_notebooks(committed: Path, executed: Path) -> list[int]:
    """Indexes of text outputs that differ (or a length mismatch as the last index); empty = identical."""
    a, b = text_outputs(committed), text_outputs(executed)
    diff = [i for i, (x, y) in enumerate(zip(a, b, strict=False)) if x != y]
    if len(a) != len(b):
        diff.append(min(len(a), len(b)))
    return diff


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--compare-notebook", nargs=2, metavar=("COMMITTED", "EXECUTED"), type=Path, required=True)
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    committed, executed = args.compare_notebook
    diff = compare_notebooks(committed, executed)
    if diff:
        a, b = text_outputs(committed), text_outputs(executed)
        for i in diff[:5]:
            logger.error(
                "Text output %d differs:\n--- committed\n%s\n+++ executed\n%s",
                i,
                a[i] if i < len(a) else "<missing>",
                b[i] if i < len(b) else "<missing>",
            )
        return 1
    logger.info("All %d text outputs identical (images not compared)", len(text_outputs(executed)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
